#!/usr/bin/env node
/**
 * roundtrip.mjs — pitch-axis engine round-trip driver (set 014 session 3).
 *
 *   export  : the Twinline compact fixture, loaded through CNBConfigIO the
 *             way the UI loads it, exported with CNBLilypond.generate()
 *   engrave : lilypond -dbackend=svg, run from the engine repo root (so
 *             \include "ChromaticNotationBase.ly" resolves) with -I here
 *   harvest : the engine's tools/harvest_svg.py
 *   measure : measure.mjs (engine positions vs the preview's axis model)
 *
 * Usage (from anywhere):
 *   node docs/sessions/session-003/roundtrip/roundtrip.mjs <engine-repo-dir>
 * Needs lilypond 2.24.2 and python on PATH. Writes its products next to
 * this script and exits with measure.mjs's status.
 */

import { readFileSync, writeFileSync } from "fs";
import { spawnSync } from "child_process";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..", "..", "..", "..");
const FIXTURE = path.join(REPO, "cnb", "assets", "examples", "gallery", "twinline-compact.json");
const ENGINE = process.argv[2];
if (!ENGINE) {
  console.error("usage: node roundtrip.mjs <engine-repo-dir>");
  process.exit(2);
}

const { CNBConfigIO } = await import(pathToFileURL(path.join(REPO, "cnb", "ui", "config-io.js")));
const { CNBLilypond } = await import(pathToFileURL(path.join(REPO, "cnb", "src", "cnb-lilypond.js")));

// 1. Export the fixture, and a CONTROL export of the same fixture with every
// xOffsetStaffSpaces removed: a shared-position chord pair is already
// separated by LilyPond's own arrangement, so the offset's effect is the
// separation difference between the two renders (the engine set-008 s2
// test-vs-control method).
const { config, validation } = CNBConfigIO.loadFromText(readFileSync(FIXTURE, "utf8"));
if (!validation.valid) throw new Error("fixture invalid: " + validation.errors.join("; "));
writeFileSync(path.join(HERE, "twinline-compact-config.ly"), CNBLilypond.generate(config));
const control = JSON.parse(JSON.stringify(config));
for (const rule of control.noteheadRules) delete rule.apply.xOffsetStaffSpaces;
writeFileSync(path.join(HERE, "twinline-compact-control-config.ly"), CNBLilypond.generate(control));

// 2. Score: every chromatic pitch c'..c''' as a single note (placement and
// stem direction), the five shared-position pairs plus one across the
// octave as chords (x-offset separation), under \key g \major (signature
// marks placed and selected through the hook). The control score is the
// same music over the control export.
const scoreFor = (configFile) => String.raw`\version "2.24.2"

%% Round-trip score for the Twinline compact fixture (set 014 session 3).
%% Generated by roundtrip.mjs — do not edit by hand.

\include "${configFile}"
\include "cnb/test-ids.ly"

%% One system on one page, so the whole score is one SVG to harvest.
\paper { page-breaking = #ly:one-line-breaking }

\score {
  \new Staff {
    \time 4/4
    \key g \major
    c'4 cis' d' dis' | e' f' fis' g' | gis' a' ais' b' |
    c'' cis'' d'' dis'' | e'' f'' fis'' g'' | gis'' a'' ais'' b'' |
    c'''1 |
    <c' cis'>4 <dis' e'> <f' fis'> <gis' a'> | <ais' b'> <c'' cis''> r2 |
  }
  \layout {
    \context {
      \Staff
      \omit TimeSignature
    }
  }
}
`;
writeFileSync(path.join(HERE, "twinline-roundtrip-score.ly"), scoreFor("twinline-compact-config.ly"));
writeFileSync(path.join(HERE, "twinline-roundtrip-control-score.ly"), scoreFor("twinline-compact-control-config.ly"));

function run(cmd, args, cwd) {
  console.log(`$ ${cmd} ${args.join(" ")}`);
  const r = spawnSync(cmd, args, { cwd, encoding: "utf8", timeout: 300000,
    env: { ...process.env, PYTHONIOENCODING: "utf-8" } });
  if (r.error) throw r.error;
  if (r.status !== 0) {
    console.error(r.stdout, r.stderr);
    throw new Error(`${cmd} exited ${r.status}`);
  }
  return r;
}

// 3–4. Engrave and harvest both renders.
for (const name of ["twinline-roundtrip", "twinline-roundtrip-control"]) {
  const outBase = path.join(HERE, name);
  run("lilypond", ["-dbackend=svg", "-I", HERE, "-o", outBase,
    path.join(HERE, `${name}-score.ly`)], ENGINE);
  run("python", [path.join(ENGINE, "tools", "harvest_svg.py"), outBase + ".svg",
    "-o", `${outBase}.harvested.json`, "--pretty"], ENGINE);
}
const harvested = path.join(HERE, "twinline-roundtrip.harvested.json");

// 5. Measure.
const m = spawnSync(process.execPath, [path.join(HERE, "measure.mjs"), harvested],
  { stdio: "inherit", env: process.env });
process.exit(m.status ?? 1);
