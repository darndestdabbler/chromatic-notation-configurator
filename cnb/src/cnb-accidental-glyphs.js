export const CNBAccidentalGlyphs = {

  /** Font units per staff space in every size. */
  UNITS_PER_STAFF_SPACE: 250,

  /**
   * The optical size LilyPond draws a staff magnified m with: the design
   * size nearest 20 pt × m by ratio (the largest above emmentaler-26's, the
   * smallest below emmentaler-11's).
   *
   * @param {number} m  the staff's magnification (engine.defaultMagnify)
   * @returns {number}  the size's name: 11, 13, 14, 16, 18, 20, 23 or 26
   */
  designSize(m) {
    const want = 20 * (Number.isFinite(m) && m > 0 ? m : 1);
    let best = DESIGNS[0];
    for (const d of DESIGNS) {
      if (Math.abs(Math.log(d.design / want)) < Math.abs(Math.log(best.design / want))) best = d;
    }
    return best.size;
  },

  /**
   * A sign at a magnification: its SVG path in font units and its extents
   * in staff spaces.
   *
   * @param {"sharp"|"flat"} sign
   * @param {number} m  the staff's magnification
   * @returns {{path:string, x:[number, number], y:[number, number]}}
   */
  glyph(sign, m) {
    const size = CNBAccidentalGlyphs.designSize(m);
    return DESIGNS.find(d => d.size === size)[sign];
  },
};
